// — ดู roleTierOf_ ใน gas-backend-COMPLETE-v3/Utils.gs):
//   1. 'admin'  = ผู้ดูแลระบบเต็มรูปแบบ (จัดการผู้ใช้งาน, ลบรายการ, ดู Audit Log,
//                 ดูสถิติ RPA Bot, เห็นทุกรายการ)
//   2. 'full'   = เห็นรายการของทุกคนในหน้ารายงานได้ (ไม่ใช่แค่ของตัวเอง) แต่ไม่มี
//                 สิทธิ์ผู้ดูแลระบบข้อ 1 ด้านบน
//   3. 'normal' = ที่เหลือ (เช่น ครูผู้สอน) เห็นเฉพาะรายการที่ตัวเองบันทึก
//
// เดิมไฟล์นี้เก็บรายชื่อ role ดิบ (ADMIN_ROLES/FULL_VISIBILITY_ROLES) เองซ้ำกับ
// Utils.gs ฝั่งเซิร์ฟเวอร์เป๊ะๆ เสี่ยงแก้ที่นึงแล้วลืมอีกที่ ทำให้เมนู/สิทธิ์ที่เห็น
// ในหน้าเว็บไม่ตรงกับสิทธิ์จริงที่ backend บังคับ (บังคับจริงอยู่ฝั่ง backend เสมอ
// ไฟล์นี้เป็นแค่ชั้นป้องกัน UI เท่านั้น) ตอนนี้เซิร์ฟเวอร์เป็นเจ้าของข้อมูลจริงที่
// เดียว แนบ roleTier มากับ user object ให้เลยตอน login ไฟล์นี้แค่เช็ก roleTier
// นั้น ไม่ต้องเก็บรายชื่อ role เองอีกต่อไป
//
// ⚠️ บัญชีที่ login ค้างไว้จากก่อน deploy การเปลี่ยนแปลงนี้จะยังไม่มี roleTier
// ติดมาใน currentUser (localStorage) จนกว่าจะออกจากระบบแล้วเข้าใหม่ — ระหว่างนั้น
// เมนูเฉพาะผู้ดูแลระบบจะถูกซ่อนไปก่อนเฉยๆ ไม่กระทบความปลอดภัยเพราะฝั่งเซิร์ฟเวอร์
// ยังบังคับด้วย requireAdmin()/requireSession() อยู่แล้วเป็นด่านจริง
export function isAdmin(user) {
  return !!user && user.roleTier === 'admin';
}

// ใช้ตัดสินว่าควรเห็นรายการของทุกคนในหน้ารายงานไหม (admin เต็มรูปแบบ หรือกลุ่ม
// เห็นทุกรายการ) — ต่างจาก isAdmin() ที่เข้มกว่า (แค่ผู้ดูแลระบบเต็มรูปแบบเท่านั้น)
export function canViewAllRecords(user) {
  return !!user && (user.roleTier === 'admin' || user.roleTier === 'full');
}

export function roleTierLabel(user) {
  if (isAdmin(user)) return 'ผู้ดูแลระบบ';
  if (canViewAllRecords(user)) return 'เห็นทุกรายการ';
  return 'ผู้ใช้งานทั่วไป';
}

