// สิทธิ์การเข้าถึงระบบ แบ่งเป็น 3 ระดับ:
//   1. ADMIN_ROLES           = ผู้ดูแลระบบเต็มรูปแบบ (จัดการผู้ใช้งาน, ลบรายการ,
//                              ดู Audit Log, ดูสถิติ RPA Bot, เห็นทุกรายการ)
//   2. FULL_VISIBILITY_ROLES = เห็นรายการของทุกคนในหน้ารายงานได้ (ไม่ใช่แค่ของ
//                              ตัวเอง) แต่ไม่มีสิทธิ์ผู้ดูแลระบบข้อ 1 ด้านบน
//   3. ที่เหลือ (เช่น ครูผู้สอน) = เห็นเฉพาะรายการที่ตัวเองบันทึก
//
// 'Admin' และ 'บุคลากรงานปกครอง' เก็บไว้ในนี้เพื่อรองรับบัญชีเก่าที่ยังตั้งค่าเป็น
// ค่านี้อยู่ในชีต Users เท่านั้น — บัญชีใหม่ให้ใช้ "ผู้ดูแลระบบ" / "เจ้าหน้าที่งาน
// ปกครอง" แทน (ไม่โชว์ 'Admin'/'บุคลากรงานปกครอง' เป็นตัวเลือกในหน้าจัดการผู้ใช้งาน
// อีกต่อไป ดู ALL_ROLES ด้านล่าง)
export const ADMIN_ROLES = ['Admin', 'ผู้ดูแลระบบ', 'บุคลากรงานปกครอง', 'เจ้าหน้าที่งานปกครอง', 'หัวหน้างานปกครอง'];

// เห็นรายการของทุกคนได้ในหน้ารายงาน (ตามลำดับชั้นการบังคับบัญชาจริงที่ต้องดูแล
// ภาพรวมทั้งวิทยาลัย) แต่ไม่มีสิทธิ์จัดการผู้ใช้งาน/ลบรายการ/ดู Audit Log
export const FULL_VISIBILITY_ROLES = ['ครูปกครอง', 'ผู้อำนวยการสถานศึกษา', 'รองผู้อำนวยการสถานศึกษา'];

export const TEACHER_ROLES = ['ครูผู้สอน'];

export function isAdmin(user) {
  return !!user && ADMIN_ROLES.includes(user.role);
}

// ใช้ตัดสินว่าควรเห็นรายการของทุกคนในหน้ารายงานไหม (admin เต็มรูปแบบ หรือกลุ่ม
// เห็นทุกรายการ) — ต่างจาก isAdmin() ที่เข้มกว่า (แค่ผู้ดูแลระบบเต็มรูปแบบเท่านั้น)
export function canViewAllRecords(user) {
  return !!user && (ADMIN_ROLES.includes(user.role) || FULL_VISIBILITY_ROLES.includes(user.role));
}

export function roleTierLabel(user) {
  if (isAdmin(user)) return 'ผู้ดูแลระบบ';
  if (canViewAllRecords(user)) return 'เห็นทุกรายการ';
  return 'ผู้ใช้งานทั่วไป';
}

// รายการบทบาทให้เลือกตอนสร้าง/แก้ไขผู้ใช้งาน — ไม่รวม 'Admin' และ 'บุคลากรงานปกครอง'
// (ค่าเก่า เก็บไว้แค่ให้บัญชีเดิมยังใช้งานได้ ไม่ให้เลือกซ้ำอีกต่อไป) และไม่รวม
// 'ครูที่ปรึกษา' (ยกเลิกบทบาทนี้แล้ว — บัญชีเก่าที่ยังตั้งเป็นค่านี้อยู่จะกลาย
// เป็น "เห็นเฉพาะรายการของตัวเอง" แบบเดียวกับครูผู้สอนโดยอัตโนมัติ ปลอดภัยไว้ก่อน
// แต่แนะนำให้เข้าไปเปลี่ยนบทบาทบัญชีเหล่านั้นเป็นอย่างอื่นด้วยตอนสะดวก)
export const ALL_ROLES = [
  'ครูผู้สอน',
  'ครูปกครอง',
  'หัวหน้างานปกครอง',
  'เจ้าหน้าที่งานปกครอง',
  'รองผู้อำนวยการสถานศึกษา',
  'ผู้อำนวยการสถานศึกษา',
  'ผู้ดูแลระบบ',
];
