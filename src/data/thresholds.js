// เกณฑ์ผลของคะแนนสะสม — อ้างอิงระเบียบวิทยาลัยเทคนิคสมุทรสาครว่าด้วยหลักเกณฑ์
// การพิจารณาลงโทษนักเรียน นักศึกษา พ.ศ. 2566 ข้อ 8.3
//
// หมายเหตุ: ระเบียบให้นับคะแนนสะสม "ตลอดปีการศึกษา" แล้วรีเซ็ตเมื่อขึ้นปีการศึกษา
// ใหม่ (เว้นทัณฑ์บนที่ยังคงประวัติถาวร) — ระบบปัจจุบันยังไม่มีการแบ่งข้อมูลตามปี
// การศึกษา ตัวเลขด้านล่างจึงเป็นยอดสะสม "จากทุกรายการที่มีอยู่ในระบบ" ไปก่อน
// (จุดนี้ต้องเพิ่มคอลัมน์ปีการศึกษาใน Google Sheets ถึงจะแยกตามปีได้จริง)
export const THRESHOLDS = [
  { min: 15, max: 19, ref: 'ข้อ 8.3(1)', action: 'แจ้งผู้ปกครองรับทราบ', tone: 'notice' },
  { min: 20, max: 29, ref: 'ข้อ 8.3(2)', action: 'เชิญผู้ปกครองทำทัณฑ์บน + เข้าร่วมกิจกรรมปรับเปลี่ยนพฤติกรรม', tone: 'warn' },
  { min: 30, max: 30, ref: 'ข้อ 8.3(3)', action: 'เชิญผู้ปกครองทำทัณฑ์บน + กิจกรรมจิตอาสา', tone: 'warn' },
  { min: 31, max: Infinity, ref: 'ข้อ 8.3(4)', action: 'ความผิดสถานหนัก — พิจารณาย้ายสถานศึกษา', tone: 'critical' },
];

export function statusForPoints(points) {
  for (let i = THRESHOLDS.length - 1; i >= 0; i--) {
    if (points >= THRESHOLDS[i].min) return THRESHOLDS[i];
  }
  return null;
}
